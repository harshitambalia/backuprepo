create or replace TABLE DEV_PROJECTS (
	PROJECT_ID NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 noorder,
	PROJECT_NAME VARCHAR(255),
	START_DATE DATE,
	END_DATE DATE,
	STATUS VARCHAR(50),
	MANAGER_ID NUMBER(38,0),
	CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	primary key (PROJECT_ID),
	foreign key (MANAGER_ID) references MY_DBT_EXPERIMENT_DB.PUBLIC.DEV_USERS(USER_ID)
);