create or replace TABLE DEV_COMMENTS (
	COMMENT_ID NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 noorder,
	TASK_ID NUMBER(38,0),
	USER_ID NUMBER(38,0),
	COMMENT_TEXT VARCHAR(500),
	CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	primary key (COMMENT_ID),
	foreign key (TASK_ID) references MY_DBT_EXPERIMENT_DB.PUBLIC.DEV_TASKS(TASK_ID),
	foreign key (USER_ID) references MY_DBT_EXPERIMENT_DB.PUBLIC.DEV_USERS(USER_ID)
);