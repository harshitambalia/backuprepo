create or replace TABLE DEV_FILES (
	FILE_ID NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 noorder,
	PROJECT_ID NUMBER(38,0),
	TASK_ID NUMBER(38,0),
	UPLOADED_BY NUMBER(38,0),
	FILE_NAME VARCHAR(255),
	FILE_URL VARCHAR(500),
	UPLOADED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	primary key (FILE_ID),
	foreign key (PROJECT_ID) references MY_DBT_EXPERIMENT_DB.PUBLIC.DEV_PROJECTS(PROJECT_ID),
	foreign key (TASK_ID) references MY_DBT_EXPERIMENT_DB.PUBLIC.DEV_TASKS(TASK_ID),
	foreign key (UPLOADED_BY) references MY_DBT_EXPERIMENT_DB.PUBLIC.DEV_USERS(USER_ID)
);