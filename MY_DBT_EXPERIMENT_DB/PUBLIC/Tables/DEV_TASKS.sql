create or replace TABLE DEV_TASKS (
	TASK_ID NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 noorder,
	PROJECT_ID NUMBER(38,0),
	ASSIGNED_TO NUMBER(38,0),
	TASK_NAME VARCHAR(255),
	DUE_DATE DATE,
	PRIORITY VARCHAR(50),
	STATUS VARCHAR(50),
	CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	primary key (TASK_ID),
	foreign key (PROJECT_ID) references MY_DBT_EXPERIMENT_DB.PUBLIC.DEV_PROJECTS(PROJECT_ID),
	foreign key (ASSIGNED_TO) references MY_DBT_EXPERIMENT_DB.PUBLIC.DEV_USERS(USER_ID)
);