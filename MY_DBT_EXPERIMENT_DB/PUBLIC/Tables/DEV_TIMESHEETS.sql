create or replace TABLE DEV_TIMESHEETS (
	TIMESHEET_ID NUMBER(38,0) NOT NULL autoincrement start 1 increment 1 noorder,
	USER_ID NUMBER(38,0),
	TASK_ID NUMBER(38,0),
	HOURS_WORKED NUMBER(5,2),
	WORK_DATE DATE,
	CREATED_AT TIMESTAMP_NTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	primary key (TIMESHEET_ID),
	foreign key (USER_ID) references MY_DBT_EXPERIMENT_DB.PUBLIC.DEV_USERS(USER_ID),
	foreign key (TASK_ID) references MY_DBT_EXPERIMENT_DB.PUBLIC.DEV_TASKS(TASK_ID)
);